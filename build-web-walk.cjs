// Regenerate browser-sized whole-pose atlases from the reviewed Windows sources.
const fs=require('node:fs');
const path=require('node:path');
const crypto=require('node:crypto');
const {createRequire}=require('node:module');
const {chromium}=createRequire(path.resolve(process.argv[2]||'.','package.json'))('playwright');
const root=__dirname, names=['naranja','gris','calico','negro','blanco','tuxedo','siames','marron'];
const sizes=[1,.96,1.04,.98,1.05,.95,1.02,1];
const hash=buffer=>crypto.createHash('sha256').update(buffer).digest('hex');
(async()=>{
  const browser=await chromium.launch({headless:true});
  try{
    const page=await browser.newPage();
    const coats=[],provenance=[];
    for(const [index,name] of names.entries()){
      const source=fs.readFileSync(path.join(root,'desktop/assets/walk-'+name+'.png'));
      const packed=await page.evaluate(async encoded=>{
        const image=new Image();image.src='data:image/png;base64,'+encoded;await image.decode();
        const canvas=document.createElement('canvas');canvas.width=896;canvas.height=299;
        const g=canvas.getContext('2d',{willReadFrequently:true});
        g.imageSmoothingEnabled=true;g.imageSmoothingQuality='high';
        g.drawImage(image,0,0,896,image.height*896/image.width);
        const pixels=g.getImageData(0,0,896,299).data,frames=[];
        let maxHeight=0,maxLeft=0,maxRight=0;
        for(let frame=0;frame<8;frame++){
          const col=frame%4,row=Math.floor(frame/4),left=col*224,right=left+224;
          const top=Math.floor(row*299/2),bottom=Math.floor((row+1)*299/2),anchor=224*800/1536;
          let x0=right,y0=bottom,x1=left,y1=top;
          for(let y=top;y<bottom;y++)for(let x=left;x<right;x++)if(pixels[(y*896+x)*4+3]>=32){
            x0=Math.min(x0,x);y0=Math.min(y0,y);x1=Math.max(x1,x);y1=Math.max(y1,y);
          }
          if(x1<=x0||y1<=y0)throw Error('Empty pose '+frame);
          x0=Math.max(left,x0-1);y0=Math.max(top,y0-1);x1=Math.min(right-1,x1+1);y1=Math.min(bottom-1,y1+1);
          const w=x1-x0+1,h=y1-y0+1,offset=anchor-(x0-left);
          frames.push({x:x0,y:y0,w,h,anchorX:offset/w,anchorY:1});
          maxHeight=Math.max(maxHeight,h);maxLeft=Math.max(maxLeft,offset);maxRight=Math.max(maxRight,w-offset);
        }
        return {png:canvas.toDataURL('image/png').split(',')[1],frames,scale:.23*Math.min(68/maxHeight,50/maxLeft,50/maxRight)};
      },source.toString('base64'));
      const png=Buffer.from(packed.png,'base64'),url='assets/walk-'+name+'.png';
      fs.writeFileSync(path.join(root,url),png);
      coats.push({name,url,size:sizes[index],stride:13.8*sizes[index],scale:packed.scale*sizes[index],frames:packed.frames});
      provenance.push({name,source:'desktop/assets/walk-'+name+'.png',sourceSha256:hash(source),url,sha256:hash(png),bytes:png.length});
    }
    fs.writeFileSync(path.join(root,'walk-data.js'),'/* Generated by build-web-walk.cjs; complete poses, fixed source anchor. */\nwindow.PARK_WALK = '+JSON.stringify({coats},null,2)+';\n'+
      'window.ParkWalk = Object.freeze({\n  size: i => window.PARK_WALK.coats[i].size,\n  stride: i => window.PARK_WALK.coats[i].stride,\n  frame: (distance, i) => Math.floor((((distance / window.PARK_WALK.coats[i].stride) % 1) + 1) % 1 * 8 + 1e-9) % 8\n});\n');
    fs.writeFileSync(path.join(root,'assets/walk-provenance.json'),JSON.stringify({method:'Uniform whole-image reduction to width 896; alpha crop >=32 with one-pixel margin. Native scale multiplied by 0.23; source canvas anchor retained. No limbs redrawn.',coats:provenance},null,2)+'\n');
    console.log(JSON.stringify({coats:coats.length,frames:coats.length*8,bytes:provenance.reduce((n,c)=>n+c.bytes,0)}));
  }finally{await browser.close()}
})().catch(error=>{console.error(error);process.exitCode=1});
